# ── schema walk ──


def _is_model(t: object) -> bool:
    return isinstance(t, type) and issubclass(t, BaseModel)


def _unwrap_optional(t: object) -> tuple[object, bool]:
    """`X | None` → (X, True); anything else → (t, False)."""
    if typing.get_origin(t) in (typing.Union, types.UnionType):
        args = [a for a in typing.get_args(t) if a is not type(None)]
        if len(args) == 1:
            return args[0], True
    return t, False


def _type_str(t: object, field) -> str:
    t, optional = _unwrap_optional(t)
    origin = typing.get_origin(t)
    if origin is typing.Literal:
        out = "one of: " + ", ".join(f"`{a}`" for a in typing.get_args(t))
    elif origin is list:
        out = f"list of {_type_str(typing.get_args(t)[0], None)}"
    elif origin is dict:
        k, v = typing.get_args(t)
        out = f"map of {_type_str(k, None)} → {_type_str(v, None)}"
    elif _is_model(t):
        out = "block"
    elif t is dict:
        out = "object"
    else:
        out = getattr(t, "__name__", str(t))
    if field is not None:
        out += _constraints(field)
    return out + (", optional" if optional else "")


def _constraints(field) -> str:
    lo = hi = None
    bits = []
    for m in field.metadata:
        lo = getattr(m, "ge", lo)
        hi = getattr(m, "le", hi)
        if getattr(m, "pattern", None):
            bits.append(f"matches `{m.pattern}`")
        if getattr(m, "min_length", None):
            bits.append(f"at least {m.min_length}")
    if lo is not None or hi is not None:
        bits.insert(0, f"{lo if lo is not None else ''}–{hi if hi is not None else ''}")
    return f" ({'; '.join(bits)})" if bits else ""


def _default_str(field) -> str:
    if field.default_factory is not None:
        v = field.default_factory()
    elif field.default is PydanticUndefined:
        return "**required**"
    elif field.default is None:
        return "absent"
    else:
        v = field.default
    return '`""`' if v == "" else f"`{v!r}`"


def walk(model: type[BaseModel], prefix: str = "") -> list[dict]:
    """Leaf rows in declaration order. A nested block gets a row of its own
    only when it is optional (absence means something); required blocks
    appear through their leaves."""
    rows: list[dict] = []
    for name, field in model.model_fields.items():
        # The key as platform.yaml writes it: a field named apart from its key (a
        # Python keyword) carries the key as its alias.
        key = f"{prefix}{field.alias or name}"
        inner, optional = _unwrap_optional(field.annotation)
        if _is_model(inner):
            if optional:
                rows.append(_row(key, field))
            rows.extend(walk(inner, key + "."))
        else:
            rows.append(_row(key, field))
    return rows


def _row(key: str, field) -> dict:
    return {
        "key": key,
        "type": _type_str(field.annotation, field),
        "default": _default_str(field),
        "env": ENV.get(key, ""),
        "desc": DESCRIPTIONS.get(key, TODO),
        "footprint": key in FOOTPRINT,
    }


def sections(model: type[BaseModel]) -> list[tuple[str, list[dict]]]:
    """One section per top-level block; root scalars go first as 'Top level'."""
    rows = walk(model)
    blocks = [
        n
        for n, f in model.model_fields.items()
        if _is_model(_unwrap_optional(f.annotation)[0])
    ]
    out = [
        (
            "Top level",
            [r for r in rows if "." not in r["key"] and r["key"] not in blocks],
        )
    ]
    for name in blocks:
        out.append((name, [r for r in rows if r["key"].split(".")[0] == name]))
    return out


# ── consistency guards (raise: a wrong reference must not be writable) ──


def check_env_table(model: type[BaseModel]) -> None:
    # source.image and source.build are mutually exclusive, so ONE manifest can
    # never emit both env names: take the union of the two shapes.
    import copy

    with_image = copy.deepcopy(_FULL)
    with_image["migration"]["source"].pop("build")
    with_image["migration"]["source"]["image"] = "registry.example.com/team/agent:1"
    emitted = set(pc.to_env(model.model_validate(_FULL))) | set(
        pc.to_env(model.model_validate(with_image))
    )
    listed = set(ENV.values()) | LEGACY_ENV
    if emitted != listed:
        raise SystemExit(
            f"ENV table drifted from to_env(): missing={sorted(emitted - listed)} "
            f"stale={sorted(listed - emitted)}"
        )


def check_description_keys(model: type[BaseModel]) -> list[str]:
    keys = {r["key"] for r in walk(model)}
    stale = sorted((set(DESCRIPTIONS) | set(ENV) | FOOTPRINT) - keys)
    if stale:
        raise SystemExit(f"generator tables name keys the model does not have: {stale}")
    return sorted(k for k in keys if k not in DESCRIPTIONS)


# ── render ──

INTRO = """\
# platform.yaml reference

`platform.yaml` is the one file that describes a deployment: project identity,
account strategy, IdP, agent pattern, gateway tools, security controls,
observability, and (for a migration) the agent you are bringing. Everything
else — the stack list, verification, the dashboard, destroy — is derived from
it, so a typo'd key is an error and every failure in the file is reported at
once.

You rarely write it from scratch: `deploy.sh design --profile <name>` writes it
from the matching `presets/<name>.yaml` (the presets are embedded verbatim at
the end of this page). Edit the result, then validate without touching AWS:

```bash
python -m infra_utils.platform_config platform.yaml
```

Precedence when a value is set in more than one place:
`cdk context > env var > platform.yaml > defaults`. The **Env override**
column is the name `to_env()` exports for each key — the same name `deploy.sh`
and `app.py` read, so an exported variable wins over the file for that run
only. Keys marked ✦ change **which stacks** are deployed
(`expected_stacks()`), not just how a stack is configured; a plan is printed
before anything is created.
"""

LEGEND = (
    "✦ changes the deployment footprint (the set of stacks), see `expected_stacks()`."
)


def _table(rows: list[dict]) -> list[str]:
    out = [
        "| Key | Type | Default | Env override | Description |",
        "|---|---|---|---|---|",
    ]
    for r in rows:
        key = f"`{r['key']}`" + (" ✦" if r["footprint"] else "")
        env = f"`{r['env']}`" if r["env"] else "—"
        out.append(f"| {key} | {r['type']} | {r['default']} | {env} | {r['desc']} |")
    return out


def render(model: type[BaseModel] = pc.PlatformConfig, presets: Path = PRESETS) -> str:
    check_env_table(model)
    check_description_keys(model)
    lines = [INTRO, LEGEND, ""]
    for title, rows in sections(model):
        heading = title if title == "Top level" else f"`{title}:`"
        doc = _block_doc(model, title)
        lines += [f"## {heading}", ""]
        if doc:
            lines += [doc, ""]
        lines += _table(rows) + [""]
    lines += [
        "## Presets",
        "",
        "Each preset is a complete, validated `platform.yaml`; `--profile <name>` copies it for you.",
        "",
    ]
    for p in sorted(presets.glob("*.yaml")):
        lines += [
            "<details>",
            f"<summary><code>presets/{p.name}</code></summary>",
            "",
            "```yaml",
            p.read_text().rstrip("\n"),
            "```",
            "",
            "</details>",
            "",
        ]
    lines += [FOOTER, ""]
    return "\n".join(lines)


def _block_doc(model: type[BaseModel], name: str) -> str:
    """First paragraph of a block model's docstring, if it has one."""
    field = model.model_fields.get(name)
    if field is None:
        return ""
    inner, _ = _unwrap_optional(field.annotation)
    doc = (inner.__doc__ or "").strip()
    if not doc or doc.startswith("Usage docs:"):  # pydantic's BaseModel default
        return ""
    return " ".join(doc.split("\n\n")[0].split())


def main(argv: list[str]) -> int:
    text = render()
    if "--check" in argv:
        current = OUT.read_text() if OUT.exists() else ""
        if current == text:
            return 0
        sys.stdout.writelines(
            difflib.unified_diff(
                current.splitlines(True),
                text.splitlines(True),
                str(OUT.relative_to(ROOT)),
                "generated",
            )
        )
        print(
            f"\n{OUT.relative_to(ROOT)} is stale; run scripts/gen_platform_reference.py"
        )
        return 1
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
